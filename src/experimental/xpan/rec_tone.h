#ifndef R5_REC_TONE_H
#define R5_REC_TONE_H
#include <stdint.h>
#include "tone_gen.h"

/* Issue #14 movie record indicator (opt-in --record-indicator). Owner of the
 * one-time PCM/descriptor publication, the AudioCtrl-masked preflight, the
 * non-blocking submit/observe step machine and the R5T1 counter report. Runs
 * only in the worker task; the record-state hook (rec_state.c) only increments
 * rec_press_seq. One immutable cue buffer per build, generated once by
 * tone_gen from the linked rec_tone_segments. */

/* The only change from audio.S audio_check_dependencies: AudioCtrl states 1, 4
 * and 5 are admitted for this cue (the shutter-feedback clips keep 1 << 1). */
#define REC_TONE_ACTRL_MASK ((UINT32_C(1) << 1) | (UINT32_C(1) << 4) | (UINT32_C(1) << 5))
/* SE id 2 skips the PCM worker's "Movie Playing" gate (E08B1330..E08B135C), which
 * otherwise rejects a cue while AudioCtrl is exactly 5. */
#define REC_TONE_SE_ID 2u
/* RecState values in which a pending cue may still be submitted (1 pressed,
 * 2 requested, 3 recording); any other state drops it and it is never replayed. */
#define REC_TONE_REC_STATE_MASK ((UINT32_C(1) << 1) | (UINT32_C(1) << 2) | (UINT32_C(1) << 3))
#define REC_TONE_BUSY_TICKS 10u     /* preflight retries after the first, ~200 ms */
#define REC_TONE_OBSERVE_TICKS 25u  /* observation ticks before TIMEOUT, ~500 ms */
#define REC_TONE_DESC_WORDS 16u
#define REC_TONE_DESC_BYTES 64u

/* ABeep singleton fields. Not in firmware.json: the same literal offsets
 * audio.S reads (+4 handle, +0x24 result, +0x28/+0x2C live PCM, +0x48 phase,
 * +0x4C stock test owner) plus +0x40 last PCM se_id (ROM E08B142E).
 * Output-context route flags +4/+8 (E08BC390/E08BC3A2) and +0xC. */
#define REC_TONE_ABEEP_HANDLE 0x04u
#define REC_TONE_ABEEP_RESULT 0x24u
#define REC_TONE_ABEEP_PCM_PTR 0x28u
#define REC_TONE_ABEEP_PCM_BYTES 0x2cu
#define REC_TONE_ABEEP_LAST_ID 0x40u
#define REC_TONE_ABEEP_PHASE 0x48u
#define REC_TONE_ABEEP_OWNER 0x4cu
#define REC_TONE_PHASE_ACTIVE 1u
#define REC_TONE_PHASE_STOP 2u
#define REC_TONE_PHASE_COMPLETE 3u

enum rec_tone_preflight {
    REC_TONE_PF_OK = 0,
    REC_TONE_PF_NOT_READY = 1,      /* [singleton], [ctx] or handle [ctx+4] null */
    REC_TONE_PF_BUSY = 2,           /* ABeep state != 1 or phase != 3 */
    REC_TONE_PF_STOCK_OWNED = 3,    /* [ctx+0x4C] != 0 */
    REC_TONE_PF_STATE_INVALID = 4,  /* ABeep state query returned -1 */
    REC_TONE_PF_ACTRL_MISSING = 5,  /* [0x10234] or its handle null */
    REC_TONE_PF_ACTRL_INVALID = 6,  /* AudioCtrl state query returned -1 */
    REC_TONE_PF_ACTRL_STATE = 7,    /* state outside REC_TONE_ACTRL_MASK */
    REC_TONE_PF_AUDIO_IC = 8,       /* [[0x10240]+4] != 1 */
    REC_TONE_PF_OUTPUT_CTX = 9,     /* [0x19140] == 0 */
    REC_TONE_PF_ICU_CACHE = 10,     /* ICU cache uninitialised or unknown kind */
    REC_TONE_PF_PARAM_TABLE = 11,   /* parameter table for the kind null */
    REC_TONE_PF_COUNT = 12
};
/* Preflight reasons that keep a pending cue for up to REC_TONE_BUSY_TICKS. */
#define REC_TONE_RETRY_MASK ((UINT32_C(1) << REC_TONE_PF_BUSY) | (UINT32_C(1) << REC_TONE_PF_ACTRL_STATE))

enum rec_tone_outcome {
    REC_TONE_O_NONE = 0,
    REC_TONE_O_SETTLED = 1,
    REC_TONE_O_STOPPED = 2,
    REC_TONE_O_REJECTED = 3,
    REC_TONE_O_TIMEOUT = 4,
    REC_TONE_O_CONTEXT_CHANGED = 5,
    REC_TONE_O_UNEXPECTED_PHASE = 6,
    REC_TONE_O_STATE_INVALID = 7,
    REC_TONE_O_BUFFER_CHANGED = 8,
    REC_TONE_O_SUBMIT_NONZERO = 9,
    REC_TONE_O_COUNT = 10
};

enum rec_tone_fault {
    REC_TONE_F_NONE = 0,
    REC_TONE_F_GEN = 1,      /* tone_gen_fill count mismatch: never published */
    REC_TONE_F_DESC = 2,     /* pending descriptor/buffer mismatch: never published */
    REC_TONE_F_TIMEOUT = 3,  /* observation timeout: no further submissions this boot */
    REC_TONE_F_API = 4       /* missing binding: never published */
};

enum { REC_TONE_IDLE = 0, REC_TONE_OBSERVE = 1 };

typedef uint32_t (*rec_tone_read_fn)(uint32_t address);
typedef int32_t (*rec_tone_query_fn)(uint32_t handle);
typedef int32_t (*rec_tone_beep_fn)(uint32_t se_id, const uint32_t *descriptor);
typedef void (*rec_tone_clean_fn)(const volatile void *start, uint32_t bytes);

/* Injected for host tests (same pattern as sound_worker_api). */
struct rec_tone_api {
    rec_tone_read_fn read;        /* aligned u32 load from Canon RAM */
    rec_tone_query_fn query;      /* firmware.json audio.state_query */
    rec_tone_beep_fn beep_start;  /* firmware.json audio.beep_start (SE_BeepStart) */
    rec_tone_clean_fn clean;      /* DCCMVAC by line, then DSB */
};

/* Generated by tools/record_indicator.py from config/firmware.json (audio).
 * rec_tone_segments[0 .. segment_count) fill rec_tone_pcm[0 .. padded_samples)
 * once; bytes == 2 * padded_samples. */
struct rec_tone_config {
    uint32_t segment_count, padded_samples, bytes;
    uint32_t rec_state_word, singleton_slot, audioctrl_slot, audioctrl_handle_offset;
    uint32_t audio_ic_slot, audio_ic_init_offset, output_context_slot;
    uint32_t icu_cache_base, icu_cache_kind_offset, icu_cache_init_offset;
    uint32_t icu_kind_vaif, icu_kind_ak, ak_param_slot, vaif_param_slot;
};
_Static_assert(sizeof(struct rec_tone_config) == 68u, "rec_tone config ABI");

struct rec_tone_attempt {
    uint32_t context, handle, se_id, actrl_state;
    int32_t state_before;
    uint32_t phase_before, result_before, last_id_before;
    int32_t state_after;
    uint32_t phase_after, result_after, last_id_after;
    uint32_t route[3];      /* [[0x19140]+4], +8, +0xC at submit */
    int32_t submit_rc;
    uint32_t preflight, outcome, rejection, ticks_to_active, ticks_to_settle;
};
/* Fields are sampled in preflight order; the preflight reason tells how far
 * sampling got (for example actrl_state is meaningful only for reasons >= 6). */

struct rec_tone_state {
    uint32_t publish_attempted, ready, fault, mode;
    uint32_t seen, pending, pending_ticks;
    uint32_t steps, presses, coalesced, submits, submit_nonzero;
    int32_t last_rc;
    uint32_t dropped_unready, dropped_not_recording;
    uint32_t preflight_drop[REC_TONE_PF_COUNT];
    uint32_t outcomes[REC_TONE_O_COUNT];
    uint32_t obs_ticks, active_seen, provisional_reject;
    struct rec_tone_attempt last;
};

extern const struct rec_tone_api rec_tone_api;
extern const struct rec_tone_config rec_tone_config;
extern const struct tone_segment rec_tone_segments[];
extern int16_t rec_tone_pcm[];
extern uint32_t rec_tone_descriptor[REC_TONE_DESC_WORDS];
extern struct rec_tone_state rec_tone_state;

/* Worker only. Publishes once on the first call, then one non-blocking step
 * per tick; never sleeps. */
void rec_tone_step(void);
/* Pure preflight; fills the before-snapshot fields of *a. Returns a
 * rec_tone_preflight reason. */
uint32_t rec_tone_preflight(struct rec_tone_attempt *a, uint32_t actrl_mask);

/* R5T1 counter report rows: the single owner of their text. Row order is the
 * order below; every row is one 84-byte KUWA DebugMsg record (text plus packed
 * arguments fit; tests/test_record_indicator.py checks the budget).
 * X(row, format, argument names) in emission order; the decoder
 * (tools/record_indicator_log.py) reads this table from this header. */
#define RT_FMT_BEGIN "R5T1 S=" OBSERVER_SOURCE_ID " Q=%u R=%u F=%u"
#define RT_FMT_COUNTS "R5T1 N=%u C=%u U=%u O=%u P=%u J=%u"
#define RT_FMT_DROPS "R5T1 T=%u X=%u D=%u Y=%u G=%u L=%u Z=%d"
#define RT_FMT_END "R5T1 E=%u"
#define REC_TONE_REPORT_ROWS(X) \
    X(begin, RT_FMT_BEGIN, "report ready fault") \
    X(counts, RT_FMT_COUNTS, "presses coalesced submits settled stopped rejected") \
    X(drops, RT_FMT_DROPS, "timeout other dropped_unready dropped_not_recording preflight_dropped last_preflight last_rc") \
    X(end, RT_FMT_END, "report")
/* The drops row's "other" column is the sum of exactly these outcomes. */
#define REC_TONE_OTHER_OUTCOMES(X) \
    X(REC_TONE_O_CONTEXT_CHANGED) X(REC_TONE_O_UNEXPECTED_PHASE) X(REC_TONE_O_STATE_INVALID) \
    X(REC_TONE_O_BUFFER_CHANGED) X(REC_TONE_O_SUBMIT_NONZERO)
/* R5T1 rows through observer_api.debug, inside the boot_mmu bundle. */
void rec_tone_report(unsigned reports);
#endif
