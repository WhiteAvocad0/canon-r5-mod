"""Parser/generator for the R5 conditional framing-row profile derived from an admitted ROM."""
from pathlib import Path
import hashlib
import json
import struct

ROM_BYTES = 67108864
ROM_BASE = 0xE0000000
TABLE_VA = 0xE20CFC64
TABLE_RAM = 0x0002648C
TABLE_OFFSET = TABLE_VA - ROM_BASE
TABLE_ROWS = 70
ROW_WORDS = 12
ROW_BYTES = 48
TABLE_SHA = "fbd829e896bb75a7d21193cb9b4afc81dcfb5f27a6f759628ea112626d0e2169"

# Contextual keys/index admission comes from corrected source review;
# these keys are not embedded in the twelve-word rows themselves.
ADMITTED = (
    (1, "0001"), (7, "0021"), (12, "4001"), (18, "4021"),
    (23, "5001"), (29, "5021"), (34, "6001"), (40, "6021"),
    (45, "7001"), (51, "7021"), (56, "8001"), (62, "8021"),
)


def build_profile_from_rom(
    rom_bytes: bytes,
    *,
    rom_sha256: str,
    expected_table_sha256: str = TABLE_SHA,
    caller_path: str = "<rom>",
    resolved_path: str = "<rom>",
) -> dict:
    """Derive projected framing rows from pre-admitted ROM bytes after verifying table SHA-256."""
    if len(rom_bytes) != ROM_BYTES:
        raise ValueError(f"selected ROM length mismatch: expected {ROM_BYTES}, got {len(rom_bytes)}")
    table = rom_bytes[TABLE_OFFSET : TABLE_OFFSET + TABLE_ROWS * ROW_BYTES]
    actual_table_sha = hashlib.sha256(table).hexdigest()
    if len(table) != TABLE_ROWS * ROW_BYTES or actual_table_sha != expected_table_sha256:
        raise ValueError("framing table extent/SHA256 does not match expected R5 2.2.1 table")

    rows = [list(row) for row in struct.iter_unpack("<12I", table)]
    admitted = []
    for index, key in ADMITTED:
        original = rows[index]
        height = 2 * ((original[7] * 1600 + 2439) // (2 * 2439))
        if not 0 < height < original[7] or (original[7] - height) & 1:
            raise ValueError("source height cannot produce centered even projection")
        delta = (original[7] - height) // 2
        projected = original.copy()
        for word, value in ((7, height), (9, original[9] + delta), (11, original[11] + delta)):
            if value > 0xFFFFFFFF:
                raise ValueError("projected coordinate exceeds uint32")
            projected[word] = value
        if rows.count(original) != 1 or projected in rows:
            raise ValueError("source/projected row identity collides with source inventory")
        admitted.append({"index": index, "key": key, "original": original.copy(), "projected": projected})

    if len({tuple(r["projected"]) for r in admitted}) != len(admitted):
        raise ValueError("projected row identity is ambiguous")

    return {
        "schema": "canon-r5-lab.frame-row-profile.v1",
        "source": {
            "caller_path": caller_path,
            "resolved_path": resolved_path,
            "bytes": ROM_BYTES,
            "sha256": rom_sha256,
        },
        "table": {
            "rom_va": TABLE_VA,
            "initialized_ram_va": TABLE_RAM,
            "file_offset": TABLE_OFFSET,
            "rows": TABLE_ROWS,
            "row_bytes": ROW_BYTES,
            "bytes": len(table),
            "sha256": actual_table_sha,
        },
        "policy": {
            "raw_aspect": 7,
            "changed_words": [7, 9, 11],
            "numerator": 1600,
            "denominator": 2439,
            "rounding": "nearest multiple of 2; exact source heights have no midpoint tie",
            "caller_photo_authority_bound": False,
            "final_scaler_alignment_bound": False,
            "camera_eligible": False,
        },
        "rows": rows,
        "admitted": admitted,
        "scope": "Conditional coordinate projection only; no hook, caller authority, final scaler or camera support claim.",
    }


def render_json(profile: dict) -> str:
    return json.dumps(profile, indent=2) + "\n"


def render_header(profile: dict) -> str:
    rom_sha = profile["source"]["sha256"]
    table_sha = profile["table"]["sha256"]
    lines = [
        "/* Generated by frame_row_profile.py from the admitted ROM framing table. */",
        "#ifndef XPAN_FRAME_ROW_CONSTANTS_H",
        "#define XPAN_FRAME_ROW_CONSTANTS_H",
        "#include <stdint.h>",
        f"#define XPAN_FRAME_ROW_CASE_COUNT {len(profile['admitted'])}u",
        f'#define XPAN_FRAME_ROW_SOURCE_SHA "{rom_sha}"',
        f'#define XPAN_FRAME_ROW_TABLE_SHA "{table_sha}"',
        "struct xpan_frame_row_case { uint32_t original[12]; uint32_t projected[12]; };",
        "static const struct xpan_frame_row_case xpan_frame_row_cases[XPAN_FRAME_ROW_CASE_COUNT]={",
    ]
    for item in profile["admitted"]:
        lines.append(f" /* Source row {item['index']}, contextual key {item['key']}. */")
        original = ",".join(f"{v}u" for v in item["original"])
        projected = ",".join(f"{v}u" for v in item["projected"])
        lines.append(" {{" + original + "},{" + projected + "}},")
    return "\n".join(lines + ["};", "#endif", ""])


def generated(profile: dict) -> dict[str, str]:
    return {"frame_row_profile.json": render_json(profile), "frame_row_constants.h": render_header(profile)}


def write_generated(directory: Path, profile: dict) -> None:
    directory = Path(directory)
    directory.mkdir(parents=True, exist_ok=True)
    for name, body in generated(profile).items():
        (directory / name).write_text(body)


def render_synthetic_constants_header() -> str:
    """Render deterministic synthetic 12-row geometry constants for host unit tests without ROM assets."""
    synthetic_cases = [
        ([1024, 682, 1024, 682, 1024, 682, 1024, 576, 0, 53, 0, 53], 378, 152, 152),
        ([1024, 682, 1024, 682, 1024, 682, 964, 542, 30, 70, 30, 70], 356, 163, 163),
        ([1600, 1200, 1600, 1066, 1600, 1066, 1600, 898, 0, 84, 0, 84], 590, 238, 238),
        ([1600, 1200, 1600, 1066, 1600, 1066, 1508, 846, 46, 110, 46, 110], 554, 256, 256),
        ([1600, 1200, 1408, 940, 1408, 940, 1408, 792, 0, 74, 96, 204], 520, 210, 340),
        ([1600, 1200, 1408, 940, 1408, 940, 1328, 748, 40, 96, 136, 226], 490, 225, 355),
    ]
    while len(synthetic_cases) < 12:
        idx = len(synthetic_cases)
        orig = [720, 480, 720, 480, 720, 480, 720, 360 + idx * 2, 0, 30 + idx, 0, 30 + idx]
        synthetic_cases.append((orig, 240 + idx * 2, 90, 90))
    admitted = []
    for i, (orig, h, y9, y11) in enumerate(synthetic_cases):
        proj = list(orig)
        proj[7], proj[9], proj[11] = h, y9, y11
        admitted.append({"index": i, "key": f"syn{i:02d}", "original": orig, "projected": proj})
    return render_header(
        {
            "source": {"sha256": "0" * 64},
            "table": {"sha256": "0" * 64},
            "admitted": admitted,
        }
    )
