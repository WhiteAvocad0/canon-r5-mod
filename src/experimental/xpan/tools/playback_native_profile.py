def header() -> str:
    lines = [
        "/* Generated by playback_native_profile.py; no policy implementation. */",
        "#ifndef R5_PLAYBACK_NATIVE_PROFILE_H",
        "#define R5_PLAYBACK_NATIVE_PROFILE_H",
    ]
    for k, v in CONSTANTS.items():
        lines.append(f"#define {k} 0x{v:08X}")
    for name, va, data, _entry in HOOKS:
        lines.extend([f"#define PN_{name}_VA 0x{va:08X}", f"#define PN_{name}_RESUME 0x{((va + len(bytes.fromhex(data))) | 1):08X}"])
    return "\n".join(lines + ["#endif", ""])


def inventory() -> dict:
    return {
        "schema": 1,
        "hooks": [
            {
                "va": va,
                "length": len(bytes.fromhex(raw)),
                "original_bytes": raw,
                "destination_symbol": dest,
                "resume_thumb": (va + len(bytes.fromhex(raw))) | 1,
            }
            for _, va, raw, dest in HOOKS
        ],
    }


if __name__ == "__main__":
    (HERE.parent / "playback_native_profile.h").write_text(header())
    (HERE / "playback-native-hooks.json").write_text(json.dumps(inventory(), indent=2) + "\n")
